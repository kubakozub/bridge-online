/**
 * Re-embeds public/cards/sprite.svg into the bundle as src/client/assets/cardSprite.ts.
 *
 * Use this after dropping in hand-drawn artwork (e.g. the deck produced from
 * docs/CLAUDE-DESIGN-PROMPT.md). It is the counterpart to `npm run cards`, which regenerates the
 * procedural fallback deck instead.
 *
 * Run: node scripts/embed-sprite.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = resolve(ROOT, 'public/cards/sprite.svg');
const OUT = resolve(ROOT, 'src/client/assets/cardSprite.ts');

const SUITS = ['S', 'H', 'D', 'C'];
const RANKS = ['2', '3', '4', '5', '6', '7', '8', '9', 'T', 'J', 'Q', 'K', 'A'];

const raw = readFileSync(SRC, 'utf8');

// Root ukrywamy zerowym rozmiarem, nie display:none — w Firefoksie gradienty i wzory z
// display:none nie renderuja sie w <use>. Dzisiejsza talia ich nie ma, ale kolejna moze.
const sprite = raw.replace(
  /<svg([^>]*) style="display:none"([^>]*)>/,
  '<svg$1 width="0" height="0" style="position:absolute;width:0;height:0;overflow:hidden" focusable="false"$2>',
);

// --- Contract checks: fail loudly rather than shipping a half-broken deck. -------------------
const problems = [];

for (const suit of SUITS) {
  for (const rank of RANKS) {
    if (!sprite.includes(`id="card-${suit}${rank}"`)) problems.push(`missing symbol card-${suit}${rank}`);
  }
}
if (!sprite.includes('id="card-back"')) problems.push('missing symbol card-back');
for (const suit of SUITS) {
  if (!sprite.includes(`id="suit-${suit}"`)) problems.push(`missing symbol suit-${suit}`);
}
if (/<script/i.test(sprite)) problems.push('sprite contains a <script> tag');
if (/href\s*=\s*"https?:/i.test(sprite)) problems.push('sprite references an external URL');

// The client scales cards by this viewBox; a different one would break every layout.
const viewBoxes = [...sprite.matchAll(/id="card-[A-Z0-9]+"\s+viewBox="([^"]+)"/g)].map((m) => m[1]);
const badViewBox = viewBoxes.find((v) => v.trim() !== '0 0 240 336');
if (badViewBox) problems.push(`card symbols must use viewBox "0 0 240 336", found "${badViewBox}"`);

if (problems.length) {
  console.error('embed-sprite: sprite does not satisfy the integration contract:');
  for (const p of problems) console.error('  - ' + p);
  console.error('\nSee docs/CLAUDE-DESIGN-PROMPT.md, Section 4.');
  process.exit(1);
}

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(
  OUT,
  '// AUTO-GENERATED by scripts/embed-sprite.mjs from public/cards/sprite.svg.\n' +
    '// Do not edit by hand. Regenerate the procedural deck with: npm run cards\n' +
    `export const CARD_SPRITE = ${JSON.stringify(sprite)};\n\n` +
    'export const CARD_WIDTH = 240;\n' +
    'export const CARD_HEIGHT = 336;\n' +
    'export const CARD_ASPECT = 240 / 336;\n' +
    "export const CARD_VIEWBOX = '0 0 240 336';\n",
  'utf8'
);

console.log(`embed-sprite: embedded ${(sprite.length / 1024).toFixed(1)} KB -> ${OUT}`);
