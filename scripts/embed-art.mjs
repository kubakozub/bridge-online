/**
 * Sklada public/art/*.svg w jeden sprite i wbudowuje go w bundle jako
 * src/client/assets/artSprite.ts — dokladnie tak, jak embed-sprite.mjs robi to z talia.
 *
 *   node scripts/embed-art.mjs
 *
 * DLACZEGO inline, a nie <img src="/art/x.svg"> albo background-image:
 * grafika z briefu bierze kolory ze zmiennych CSS (`fill="var(--suit-heart, #c8102e)"`), zeby
 * jeden plik dzialal w motywie jasnym i ciemnym oraz z talia czterokolorowa. Zmienne strony NIE
 * przenikaja do SVG ladowanego jako obraz zewnetrzny — w <img> renderowaly by sie same
 * fallbacki, czyli na ciemnym suknie wyskoczylyby jasne kolory. Wstrzykniety do DOM sprite
 * z <use href="#id"> dziedziczy kaskade strony i problem znika.
 *
 * Dwa rodzaje plikow w paczce, oba trafiaja do jednego sprite'a:
 *  - pliki-sprite (icons, vulnerability, connection-dot, bid-chip, card-states): ich <symbol>e
 *    sa kopiowane bez zmian, z wlasnymi ID (icon-copy, vul-ns, ...),
 *  - pliki samodzielne (avatar-01, logo-mark, ...): tresc root <svg> jest opakowywana w
 *    <symbol id="art-<nazwa>" viewBox="<viewBox roota>">.
 *
 * Favicony sa pomijane — serwowane jako pliki z korzenia public, nie sa potrzebne w DOM-ie.
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join, resolve, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ART = join(ROOT, 'public', 'art');
const OUT = join(ROOT, 'src', 'client', 'assets', 'artSprite.ts');

const SKIP = new Set(['favicon.svg', 'favicon-mono.svg']);

if (!existsSync(ART)) {
  console.error('brak public/art — najpierw: node scripts/import-art.mjs <paczka>');
  process.exit(2);
}

const symbols = []; // { id, viewBox, markup }
const problems = [];

for (const file of readdirSync(ART).filter((f) => f.endsWith('.svg') && !SKIP.has(f)).sort()) {
  const svg = readFileSync(join(ART, file), 'utf8');
  const name = basename(file, '.svg');

  if (/<script|<style|<image|<foreignObject/i.test(svg) || /href\s*=\s*"https?:/i.test(svg)) {
    problems.push(`${file}: lamie kontrakt (script/style/raster/odwolanie zewnetrzne)`);
    continue;
  }

  const found = [...svg.matchAll(/<symbol\b([^>]*)>([\s\S]*?)<\/symbol>/g)];
  if (found.length > 0) {
    for (const m of found) {
      const id = m[1].match(/\bid="([^"]+)"/)?.[1];
      const viewBox = m[1].match(/viewBox="([^"]+)"/)?.[1];
      if (!id || !viewBox) {
        problems.push(`${file}: symbol bez id lub viewBox`);
        continue;
      }
      symbols.push({ id, viewBox, markup: `<symbol id="${id}" viewBox="${viewBox}">${m[2].trim()}</symbol>` });
    }
    continue;
  }

  const root = svg.match(/<svg\b([^>]*)>([\s\S]*)<\/svg>\s*$/i);
  if (!root) {
    problems.push(`${file}: nie znaleziono root <svg>`);
    continue;
  }
  const viewBox = root[1].match(/viewBox="([^"]+)"/)?.[1];
  if (!viewBox) {
    problems.push(`${file}: root <svg> bez viewBox`);
    continue;
  }
  symbols.push({ id: `art-${name}`, viewBox, markup: `<symbol id="art-${name}" viewBox="${viewBox}">${root[2].trim()}</symbol>` });
}

// Zderzenie ID = jeden z dwoch rysunkow po cichu znika. Lepiej nie budowac wcale.
const seen = new Map();
for (const s of symbols) {
  if (seen.has(s.id)) problems.push(`zdublowane id "${s.id}"`);
  seen.set(s.id, true);
}
// Nie moze kolidowac z talia (card-*, suit-*), ktora siedzi w tym samym DOM-ie.
for (const s of symbols) {
  if (/^(card-|suit-)/.test(s.id)) problems.push(`id "${s.id}" koliduje z przestrzenia talii`);
}

if (problems.length) {
  console.error('embed-art: nie buduje sprite\'a:');
  for (const p of problems) console.error('  - ' + p);
  process.exit(1);
}

const sprite =
  // NIE display:none. Firefox nie rysuje <radialGradient>/<pattern> zdefiniowanych w ukrytym w ten
  // sposob SVG (a trick-well i table-felt ich uzywaja). Sprite ma byc w drzewie renderowania,
  // tylko o zerowym rozmiarze — klasyczna technika ukrywania sprite'ow.
  `<svg xmlns="http://www.w3.org/2000/svg" width="0" height="0" style="position:absolute;width:0;height:0;overflow:hidden" aria-hidden="true" focusable="false" data-generated="node scripts/embed-art.mjs">` +
  symbols.map((s) => s.markup).join('') +
  `</svg>`;

const ids = symbols.map((s) => s.id);
const viewBoxLines = symbols.map((s) => `  '${s.id}': '${s.viewBox}',`).join('\n');

writeFileSync(
  OUT,
  '// AUTO-GENERATED by scripts/embed-art.mjs from public/art/*.svg — nie edytowac recznie.\n' +
    '// Nowa paczka grafiki: node scripts/import-art.mjs <paczka> && node scripts/embed-art.mjs\n' +
    `export const ART_SPRITE = ${JSON.stringify(sprite)};\n\n` +
    `export const ART_IDS = ${JSON.stringify(ids)} as const;\n\n` +
    'export type ArtId = (typeof ART_IDS)[number];\n\n' +
    '/** viewBox kazdego symbolu — zewnetrzny <svg> musi go powtorzyc, inaczej <use> skaluje sie zle. */\n' +
    `export const ART_VIEWBOX: Record<ArtId, string> = {\n${viewBoxLines}\n};\n`,
  'utf8',
);

console.log(`embed-art: ${symbols.length} symboli, ${(sprite.length / 1024).toFixed(1)} KB -> ${OUT}`);
